#!/usr/bin/env python3
"""Embed the TL schema into the client for the raw MTProto plugin API.

  tools/damza/gen_tl.py

Reads Telegram/SourceFiles/mtproto/scheme/api.tl and mtproto.tl and writes
Telegram/SourceFiles/damza/plugins/tl/tl_schema_data.cpp and
tl_schema_layer.h. Run it after every
change of api.tl (a merge from upstream, a layer bump) and commit the result:
api_mtproto.cpp static_asserts that the embedded layer matches the client's.

The schema is split into chunks of less than 16000 bytes, each its own string
literal, and joined at runtime: MSVC rejects longer literals (C2026), even
when adjacent literals are concatenated by the compiler.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SCHEME = os.path.join(ROOT, 'Telegram', 'SourceFiles', 'mtproto', 'scheme')
OUT_DIR = os.path.join(ROOT, 'Telegram', 'SourceFiles', 'damza', 'plugins', 'tl')
OUT = os.path.join(OUT_DIR, 'tl_schema_data.cpp')
OUT_LAYER = os.path.join(OUT_DIR, 'tl_schema_layer.h')
CHUNK = 15000
DELIMITER = 'DZG_TL'

def chunks(text):
    result, current, size = [], [], 0
    for line in text.splitlines(keepends=True):
        encoded = len(line.encode('utf-8'))
        if encoded >= CHUNK:
            raise SystemExit('line too long for one chunk: %s' % line[:80])
        if size + encoded > CHUNK:
            result.append(''.join(current))
            current, size = [], 0
        current.append(line)
        size += encoded
    if current:
        result.append(''.join(current))
    return result

def literal(text):
    if (')%s"' % DELIMITER) in text:
        raise SystemExit('schema text contains the raw string delimiter')
    return 'R"%s(%s)%s"' % (DELIMITER, text, DELIMITER)

def main():
    api = open(os.path.join(SCHEME, 'api.tl'), encoding='utf-8').read()
    mtproto = open(os.path.join(SCHEME, 'mtproto.tl'), encoding='utf-8').read()
    layers = re.findall(r'^//\s*LAYER\s+(\d+)\s*$', api, re.M)
    if not layers:
        raise SystemExit('"// LAYER N" not found in api.tl')
    layer = int(layers[-1])
    api_chunks = chunks(api)
    mtproto_chunks = chunks(mtproto)
    lines = [
        '// This is the source code of DamZaGram for Desktop,',
        '// a fork of AyuGram for Desktop.',
        '//',
        '// GENERATED by tools/damza/gen_tl.py from mtproto/scheme/*.tl, do not edit.',
        '// Regenerate after every api.tl change: python3 tools/damza/gen_tl.py',
        '#include "damza/plugins/tl/tl_schema.h"',
        '#include "damza/plugins/tl/tl_schema_layer.h"',
        '',
        '#include <iterator>',
        '',
        'namespace Damza::Tl {',
        'namespace {',
        '',
        'const char *const kApiChunks[] = {',
    ]
    lines += ['%s,' % literal(c) for c in api_chunks]
    lines += [
        '};',
        '',
        'const char *const kMtprotoChunks[] = {',
    ]
    lines += ['%s,' % literal(c) for c in mtproto_chunks]
    lines += [
        '};',
        '',
        'QString Join(const char *const *chunks, int count) {',
        '\tauto result = QByteArray();',
        '\tfor (auto i = 0; i != count; ++i) {',
        '\t\tresult.append(chunks[i]);',
        '\t}',
        '\treturn QString::fromUtf8(result);',
        '}',
        '',
        '} // namespace',
        '',
        'int EmbeddedLayer() {',
        '\treturn kEmbeddedLayer;',
        '}',
        '',
        'QString EmbeddedApiSchema() {',
        '\treturn Join(kApiChunks, int(std::size(kApiChunks)));',
        '}',
        '',
        'QString EmbeddedMtprotoSchema() {',
        '\treturn Join(kMtprotoChunks, int(std::size(kMtprotoChunks)));',
        '}',
        '',
        '} // namespace Damza::Tl',
        '',
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    with open(OUT_LAYER, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join([
            '// This is the source code of DamZaGram for Desktop,',
            '// a fork of AyuGram for Desktop.',
            '//',
            '// GENERATED by tools/damza/gen_tl.py, do not edit.',
            '#pragma once',
            '',
            'namespace Damza::Tl {',
            '',
            'inline constexpr auto kEmbeddedLayer = %d;' % layer,
            '',
            '} // namespace Damza::Tl',
            '',
        ]))
    print('%s: layer %d, %d + %d chunks' % (os.path.relpath(OUT, ROOT), layer, len(api_chunks), len(mtproto_chunks)))
    return 0

if __name__ == '__main__':
    sys.exit(main())
