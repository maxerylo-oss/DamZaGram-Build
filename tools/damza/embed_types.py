#!/usr/bin/env python3
"""Embed docs/plugins/types/*.d.ts into the client, so "Create plugin" and
the DevTools scratchpad can copy them next to plugins for VS Code hints.

  tools/damza/embed_types.py

Writes Telegram/SourceFiles/damza/plugins/plugin_types_embedded.cpp.
Re-run it whenever a file in docs/plugins/types/ changes. Every file is
split into chunks below 8 KB (MSVC limits a single string literal to 16 KB).
"""
import glob, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TYPES = os.path.join(ROOT, 'docs', 'plugins', 'types')
OUT = os.path.join(ROOT, 'Telegram', 'SourceFiles', 'damza', 'plugins', 'plugin_types_embedded.cpp')
CHUNK = 8000
DELIMITER = 'DZG_TYPES'

def chunks(text):
    data = text.encode('utf-8')
    result, current = [], b''
    for line in data.splitlines(keepends=True):
        while len(line) > CHUNK:
            cut = CHUNK
            while cut > 0 and (line[cut] & 0xC0) == 0x80:
                cut -= 1
            if current:
                result.append(current)
                current = b''
            result.append(line[:cut])
            line = line[cut:]
        if len(current) + len(line) > CHUNK:
            result.append(current)
            current = b''
        current += line
    if current:
        result.append(current)
    return [c.decode('utf-8') for c in result]

def main():
    files = sorted(glob.glob(os.path.join(TYPES, '*.d.ts')))
    out = [
        '// This is the source code of DamZaGram for Desktop,',
        '// a fork of AyuGram for Desktop.',
        '//',
        '// Generated by tools/damza/embed_types.py from docs/plugins/types/.',
        '// Do not edit: re-run the script instead.',
        '#include "damza/plugins/plugin_types_embedded.h"',
        '',
        'namespace Damza::Plugins {',
        '',
        'std::vector<EmbeddedFile> EmbeddedTypeFiles() {',
        '\tauto result = std::vector<EmbeddedFile>();',
    ]
    for path in files:
        name = os.path.basename(path)
        text = open(path, encoding='utf-8').read()
        if (')' + DELIMITER + '"') in text:
            sys.exit('%s contains the raw string delimiter' % name)
        out.append('\t{')
        out.append('\t\tconst char *parts[] = {')
        for part in chunks(text):
            out.append('R"%s(%s)%s",' % (DELIMITER, part, DELIMITER))
        out.append('\t\t};')
        out.append('\t\tauto content = QByteArray();')
        out.append('\t\tfor (const auto part : parts) {')
        out.append('\t\t\tcontent.append(part);')
        out.append('\t\t}')
        out.append('\t\tresult.push_back({ u"%s"_q, content });' % name)
        out.append('\t}')
    out += [
        '\treturn result;',
        '}',
        '',
        '} // namespace Damza::Plugins',
        '',
    ]
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
    print('embedded %d file(s) into %s' % (len(files), os.path.relpath(OUT, ROOT)))

if __name__ == '__main__':
    main()
